#!/usr/bin/env bash
# Regenerate the pseudotime heatmaps in this folder from inputs/ (no cluster access needed).
#   1. yang          Yang et al. (2023) 28-gene panel, induced-timepoint mouse nuclei          -> yang_induced/
#   2. crossspecies  28 conserved one-to-one orthologs, human vs mouse (no strips)            -> crossspecies/
#   3. mi            every top pseudotime-associated gene per species, peak and centroid order -> mi_heatmaps/
# inputs/ were written on the cluster by code/inputs/export_heatmap_inputs_final_objects.py from the final objects
# (final_objects/Cevrim_{XMens,Human}_Only_Fib_Dec_Cells.h5ad, obs['pseudotime']) and the MI of record (README.md).
# Requires: R with VGAM, splines, parallel, pheatmap, colorRamps; Python 3 with numpy, pandas, matplotlib
# (cairosvg optional, for the PNG preview of the Yang panel).
# Run from this folder:  bash run_all.sh [NCORES] [all|yang|crossspecies|mi]
# Section 3 fits 2,334 genes on 42,290 / 47,533 nuclei; with NCORES = 14 it took 31 s (mostly reading the tables).
set -euo pipefail
cd "$(dirname "$0")"
NCORES="${1:-4}"
WHAT="${2:-all}"
C=inputs/common

# ---- 1. Yang panel, induced timepoints (uninduced excluded, pseudotime re-ranked within the subset) ----------------
if [[ "$WHAT" == all || "$WHAT" == yang ]]; then
  mkdir -p work/yang_induced yang_induced
  Y=inputs/yang
  Rscript code/yang/monocle_heatmap_repro.R "$Y/percell_genes_final.tsv.gz" "$Y/gene_peak_order.tsv" \
      work/yang_induced induced "$C/disp_table_mouse.tsv.gz"
  cp work/yang_induced/monocle_heat_aligned_trend.tsv yang_induced/heatmap_monocle_induced_z.tsv
  # single heatmap box (30 x 59.887 mm, no outline) + colorbar with 3.6 pt labels
  python code/yang/render_heatmap_box_svg.py "$Y/percell_genes_final.tsv.gz" "$Y/gene_peak_order.tsv" \
      --cells induced --zlim 3 --box 30 59.887 --matrix yang_induced/heatmap_monocle_induced_z.tsv \
      --prefix yang_induced/heatmap_monocle_induced
  mv yang_induced/heatmap_monocle_induced_z3_colorbar_30x59p887mm.svg yang_induced/heatmap_monocle_z3_colorbar_30x59p887mm.svg
  # colorbar with 5 pt labels (the box written by this call is identical and is discarded)
  python code/yang/render_heatmap_box_svg.py "$Y/percell_genes_final.tsv.gz" "$Y/gene_peak_order.tsv" \
      --cells induced --zlim 3 --box 30 59.887 --font-pt 5 --matrix yang_induced/heatmap_monocle_induced_z.tsv \
      --prefix work/yang_induced/cb5
  mv work/yang_induced/cb5_z3_colorbar_30x59p887mm.svg yang_induced/heatmap_monocle_z3_colorbar_5pt_30x59p887mm.svg
  # labelled panel: title, n (counted from the table), italic gene names, 5 pt colorbar
  N_INDUCED=$(python - "$Y/percell_genes_final.tsv.gz" <<'EOF'
import sys, pandas as pd
d = pd.read_csv(sys.argv[1], sep="\t", usecols=["timepoint"])
print(f"{int((d.timepoint != 'uninduced').sum()):,}")
EOF
)
  python code/yang/compose_heatmaps_svg.py yang_induced/heatmap_monocle_induced_labelled_30x59p887mm.svg \
      --boxes induced=yang_induced/heatmap_monocle_induced_z3_box_30x59p887mm.svg \
      --colorbar yang_induced/heatmap_monocle_z3_colorbar_5pt_30x59p887mm.svg --gap 2 --cbar-gap 2 \
      --titles "Induced timepoints" --subtitles "n = $N_INDUCED" --genes "$Y/gene_peak_order.tsv"
  python - <<'EOF' || echo "cairosvg not installed: PNG preview skipped"
import cairosvg
cairosvg.svg2png(url="yang_induced/heatmap_monocle_induced_labelled_30x59p887mm.svg",
                 write_to="yang_induced/heatmap_monocle_induced_labelled_30x59p887mm_preview.png", dpi=600, background_color="white")
EOF
fi

# ---- 2. Cross-species heatmap: Monocle smoothing per species, then render without composition strips -------------
if [[ "$WHAT" == all || "$WHAT" == crossspecies ]]; then
  mkdir -p work/crossspecies crossspecies
  X=inputs/crossspecies
  for s in human mouse; do
    Rscript code/crossspecies/monocle_conserved_smooth.R "$X/percell_${s}_sel28.tsv.gz" "$C/disp_table_${s}.tsv.gz" \
        "work/crossspecies/curves_${s}.tsv" "$NCORES"
  done
  python code/crossspecies/render_crossspecies_heatmaps_nostrips.py \
      --curves-human work/crossspecies/curves_human.tsv --curves-mouse work/crossspecies/curves_mouse.tsv \
      --genes "$X/conserved_profiles_selected_genes.csv" \
      --cells-human "$C/cells_human.tsv.gz" --cells-mouse "$C/cells_mouse.tsv.gz" \
      --no-strips --out crossspecies/crossspecies28_monocle_clip3_final_objects_nostrips \
      --note "regenerated by run_all.sh"
  python - "$X/conserved_profiles_selected_genes.csv" <<'EOF'
import sys, pandas as pd
s = pd.read_csv(sys.argv[1])
s.insert(0, "row", range(1, len(s) + 1))
s[["row", "human", "mouse", "phase", "profile_r_50bins", "pt_centroid"]].to_csv("crossspecies/crossspecies28_genes.csv", index=False)
EOF
fi

# ---- 3. MI heatmaps: every top pseudotime-associated gene (1:1-ortholog background), one panel per species ---------
if [[ "$WHAT" == all || "$WHAT" == mi ]]; then
  mkdir -p work/mi mi_heatmaps
  M=inputs/mi
  for s in human mouse; do
    Rscript code/crossspecies/monocle_conserved_smooth.R "$M/percell_${s}_topdecile.tsv.gz" "$C/disp_table_${s}.tsv.gz" \
        "work/mi/curves_${s}.tsv" "$NCORES"
  done
  for order in peak centroid; do
    python code/mi/render_full_heatmaps.py --curves-human work/mi/curves_human.tsv --curves-mouse work/mi/curves_mouse.tsv \
        --genes-human "$M/topdecile_human.csv" --genes-mouse "$M/topdecile_mouse.csv" \
        --cells-human "$C/cells_human.tsv.gz" --cells-mouse "$C/cells_mouse.tsv.gz" --order "$order" \
        --out "mi_heatmaps/mi_top_genes_heatmap_${order}_order"
  done
fi

ls -l yang_induced crossspecies mi_heatmaps 2>/dev/null || true
